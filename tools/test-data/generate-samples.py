def make_landscape(seed: int, name: str, w: int = 256, h: int = 256) -> list[list[tuple[int, int, int]]]:
    """Smooth vertical gradient + horizon line — looks vaguely sceneic and
    has enough low-frequency energy for the /health detail-score block to
    say something meaningful."""
    rng = LCG(seed)
    sky_top = (rng.byte() // 2, rng.byte() // 2 + 64, 200 + rng.byte() // 4)
    sky_bot = (200 + rng.byte() // 4, 220, 240)
    ground_top = (rng.byte() // 2 + 40, 120 + rng.byte() // 3, 50)
    ground_bot = (60 + rng.byte() // 3, 90 + rng.byte() // 3, 30)
    horizon = h // 2 + (rng.next_u32() % 30 - 15)
    px = []
    for y in range(h):
        if y < horizon:
            t = y / max(horizon - 1, 1)
            row = []
            for x in range(w):
                noise = (rng.byte() % 7) - 3
                r = int(sky_top[0] * (1 - t) + sky_bot[0] * t) + noise
                g = int(sky_top[1] * (1 - t) + sky_bot[1] * t) + noise
                b = int(sky_top[2] * (1 - t) + sky_bot[2] * t) + noise
                row.append((r, g, b))
        else:
            t = (y - horizon) / max(h - horizon - 1, 1)
            row = []
            for x in range(w):
                noise = (rng.byte() % 11) - 5
                r = int(ground_top[0] * (1 - t) + ground_bot[0] * t) + noise
                g = int(ground_top[1] * (1 - t) + ground_bot[1] * t) + noise
                b = int(ground_top[2] * (1 - t) + ground_bot[2] * t) + noise
                row.append((r, g, b))
        px.append(row)
    return px


def make_mandala(seed: int, w: int = 256, h: int = 256) -> list[list[tuple[int, int, int]]]:
    """Radial cosine pattern — heavy high-frequency content, useful for
    energy-distribution / texture-band tests."""
    rng = LCG(seed)
    arms = 4 + rng.next_u32() % 8
    cx, cy = w / 2, h / 2
    palette = [(rng.byte(), rng.byte(), rng.byte()) for _ in range(5)]
    px = []
    for y in range(h):
        row = []
        for x in range(w):
            dx, dy = x - cx, y - cy
            theta = math.atan2(dy, dx)
            r = math.hypot(dx, dy) / max(cx, cy)
            v = math.cos(arms * theta) * math.cos(r * 12.0)
            idx = int(((v + 1) / 2) * (len(palette) - 1))
            row.append(palette[idx])
        px.append(row)
    return px


def make_gradient(seed: int, w: int = 256, h: int = 256) -> list[list[tuple[int, int, int]]]:
    rng = LCG(seed)
    c1 = (rng.byte(), rng.byte(), rng.byte())
    c2 = (rng.byte(), rng.byte(), rng.byte())
    diagonal = bool(rng.next_u32() & 1)
    px = []
    for y in range(h):
        row = []
        for x in range(w):
            t = ((x + y) / (w + h)) if diagonal else (x / w)
            r = int(c1[0] * (1 - t) + c2[0] * t)
            g = int(c1[1] * (1 - t) + c2[1] * t)
            b = int(c1[2] * (1 - t) + c2[2] * t)
            row.append((r, g, b))
        px.append(row)
    return px


def make_noise(seed: int, w: int = 256, h: int = 256) -> list[list[tuple[int, int, int]]]:
    rng = LCG(seed)
    return [[(rng.byte(), rng.byte(), rng.byte()) for _ in range(w)] for _ in range(h)]


def make_pixel_art(seed: int, w: int = 256, h: int = 256) -> list[list[tuple[int, int, int]]]:
    rng = LCG(seed)
    palette = [(rng.byte(), rng.byte(), rng.byte()) for _ in range(6)]
    block = 16
    grid = [[palette[rng.next_u32() % len(palette)] for _ in range(w // block)] for _ in range(h // block)]
    px = []
    for y in range(h):
        row = []
        for x in range(w):
            row.append(grid[y // block][x // block])
        px.append(row)
    return px


def make_brand_logo(seed: int) -> list[list[tuple[int, int, int]]]:
    """Solid-colour rectangle on a contrasting background — looks like a
    placeholder brand glyph.  Variants then watermark it."""
    rng = LCG(seed)
    bg = (240 + rng.byte() % 15, 240 + rng.byte() % 15, 240 + rng.byte() % 15)
    fg = (rng.byte(), rng.byte(), rng.byte())
    w = h = 256
    cx, cy = w // 2, h // 2
    r = 80
    px = [[bg for _ in range(w)] for _ in range(h)]
    for y in range(h):
        for x in range(w):
            if (x - cx) ** 2 + (y - cy) ** 2 < r * r:
                px[y][x] = fg
    return px


def make_brand_watermark(base: list[list[tuple[int, int, int]]], seed: int) -> list[list[tuple[int, int, int]]]:
    """Re-render the brand glyph with: 1) a small 'WM' stamp painted into
    the corner (high-freq perturbation), 2) every pixel nudged by a tiny
    per-pixel delta.  /similar's robust-copy column should flag the
    result as "structure matches, detail differs"."""
    rng = LCG(seed + 17)
    h = len(base)
    w = len(base[0])
    out = [row[:] for row in base]
    # Per-pixel nudge.
    for y in range(h):
        for x in range(w):
            r, g, b = out[y][x]
            delta = rng.byte() % 6 - 3
            out[y][x] = (max(0, min(255, r + delta)), max(0, min(255, g + delta)), max(0, min(255, b + delta)))
    # Crude "WM" stamp in the bottom-right.
    for sy in range(8):
        for sx in range(16):
            x, y = w - 24 + sx, h - 16 + sy
            out[y][x] = (255 - out[y][x][0], 255 - out[y][x][1], 255 - out[y][x][2])
    return out


# ---------------------------------------------------------------------------
# Audio generators.
# ---------------------------------------------------------------------------


def tone(freq_hz: float, duration_s: float = 1.5, sample_rate: int = 44100, amplitude: float = 0.4) -> list[float]:
    n = int(duration_s * sample_rate)
    return [amplitude * math.sin(2 * math.pi * freq_hz * i / sample_rate) for i in range(n)]


def silence(duration_s: float = 1.5, sample_rate: int = 44100) -> list[float]:
    return [0.0] * int(duration_s * sample_rate)


def mix(*tracks: list[float]) -> list[float]:
    n = max(len(t) for t in tracks)
    out = [0.0] * n
    for t in tracks:
        for i, v in enumerate(t):
            out[i] += v
    norm = max(abs(v) for v in out) or 1.0
    return [v / norm * 0.8 for v in out]


def beep() -> list[float]:
    # A short two-tone beep.
    return tone(1000.0, 0.08) + silence(0.04) + tone(1500.0, 0.08)


