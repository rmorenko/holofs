@dataclass
class Sample:
    rel_path: str
    bytes_: bytes


def collect_samples(out_root: Path) -> list[Sample]:
    """Return every (relative path, bytes) we want to write under
    `out_root`."""
    samples: list[Sample] = []
    write_under = out_root

    # 1. Photos.
    photo_specs = [
        ("landscapes/mountain.png", make_landscape(1, "mountain")),
        ("landscapes/ocean.png", make_landscape(2, "ocean")),
        ("landscapes/forest.png", make_landscape(3, "forest")),
        ("landscapes/desert.png", make_landscape(4, "desert")),
        ("landscapes/tundra.png", make_landscape(5, "tundra")),
        ("abstract/mandala-a.png", make_mandala(11)),
        ("abstract/mandala-b.png", make_mandala(12)),
        ("abstract/gradient-warm.png", make_gradient(21)),
        ("abstract/gradient-cool.png", make_gradient(22)),
        ("abstract/noise-rgb.png", make_noise(31)),
        ("abstract/pixel-blocks.png", make_pixel_art(41)),
    ]
    # Brand pairs: logo + watermarked variant.
    for i in range(3):
        base = make_brand_logo(50 + i)
        photo_specs.append((f"brand-pairs/logo-{i + 1}.png", base))
        photo_specs.append((f"brand-pairs/logo-{i + 1}-wm.png", make_brand_watermark(base, 50 + i)))

    for rel, px in photo_specs:
        target = write_under / "photos" / rel
        target.parent.mkdir(parents=True, exist_ok=True)
        write_png(target, px)
        samples.append(Sample(f"photos/{rel}", target.read_bytes()))

    # 2. Audio.
    audio_specs = [
        ("music/bass.wav", tone(110.0, 2.0)),
        ("music/mid.wav", tone(660.0, 2.0)),
        ("music/treble.wav", tone(3500.0, 2.0)),
        ("music/mixed.wav", mix(tone(110.0, 2.0), tone(660.0, 2.0), tone(3500.0, 2.0))),
        ("music/chord-major.wav", mix(tone(440.0, 2.0), tone(554.0, 2.0), tone(660.0, 2.0))),
        ("music/chord-minor.wav", mix(tone(440.0, 2.0), tone(523.0, 2.0), tone(660.0, 2.0))),
        ("effects/beep.wav", beep()),
        ("effects/double-beep.wav", beep() + silence(0.1) + beep()),
        ("silence/silence-short.wav", silence(1.0)),
        ("silence/silence-long.wav", silence(3.0)),
    ]
    for rel, sig in audio_specs:
        target = write_under / "audio" / rel
        target.parent.mkdir(parents=True, exist_ok=True)
        write_wav(target, sig)
        samples.append(Sample(f"audio/{rel}", target.read_bytes()))

    # 3. Docs.
    doc_specs = [
        ("notes/note.txt", NOTE_TXT.encode("utf-8")),
        ("notes/todo.md", TODO_MD.encode("utf-8")),
        ("notes/journal.txt", JOURNAL_TXT.encode("utf-8")),
        ("spec/api-draft.txt", API_DRAFT_TXT.encode("utf-8")),
        ("spec/schema.json", SCHEMA_JSON.encode("utf-8")),
        ("legal/licence.txt", LICENCE_TXT.encode("utf-8")),
    ]
    for rel, raw in doc_specs:
        target = write_under / "docs" / rel
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(raw)
        samples.append(Sample(f"docs/{rel}", raw))

    # 4. Binaries — pack some of the docs into archives + raw fixture blobs.
    archives_dir = write_under / "binaries" / "archives"
    archives_dir.mkdir(parents=True, exist_ok=True)
    zip_target = archives_dir / "docs.zip"
    with zipfile.ZipFile(zip_target, "w", zipfile.ZIP_DEFLATED) as zf:
        zf.writestr("note.txt", NOTE_TXT)
        zf.writestr("todo.md", TODO_MD)
        zf.writestr("api-draft.txt", API_DRAFT_TXT)
    samples.append(Sample("binaries/archives/docs.zip", zip_target.read_bytes()))

    tar_target = archives_dir / "docs.tar"
    # Deterministic-ish tar: drop mtime by setting it to 0 on every member.
    with tarfile.open(tar_target, "w") as tf:
        for name, content in (
            ("note.txt", NOTE_TXT.encode("utf-8")),
            ("schema.json", SCHEMA_JSON.encode("utf-8")),
            ("licence.txt", LICENCE_TXT.encode("utf-8")),
        ):
            info = tarfile.TarInfo(name=name)
            info.size = len(content)
            info.mtime = 0
            tf.addfile(info, fileobj=_BytesReader(content))
    samples.append(Sample("binaries/archives/docs.tar", tar_target.read_bytes()))

    blobs_dir = write_under / "binaries" / "blobs"
    blobs_dir.mkdir(parents=True, exist_ok=True)
    for name, seed, size in (("fixture-small.bin", 71, 1024), ("fixture-medium.bin", 73, 16 * 1024), ("fixture-large.bin", 79, 128 * 1024)):
        target = blobs_dir / name
        rng = LCG(seed)
        target.write_bytes(bytes(rng.byte() for _ in range(size)))
        samples.append(Sample(f"binaries/blobs/{name}", target.read_bytes()))

    return samples


class _BytesReader:
    """Tiny io.BytesIO-compatible wrapper so tarfile.addfile can stream
    deterministically without us depending on io.BytesIO's quirks."""

    def __init__(self, data: bytes) -> None:
        self._buf = data
        self._pos = 0

    def read(self, n: int = -1) -> bytes:
        if n < 0:
            chunk = self._buf[self._pos :]
            self._pos = len(self._buf)
            return chunk
        chunk = self._buf[self._pos : self._pos + n]
        self._pos += len(chunk)
        return chunk


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument(
        "--out",
        default=os.path.join(os.path.dirname(__file__), "..", "..", "samples"),
        help="output directory (default: <repo>/samples/)",
    )
    args = ap.parse_args()
    out_root = Path(args.out).resolve()
    if out_root.exists():
        # Wipe the previous run so we never serve stale bytes.
        import shutil

        shutil.rmtree(out_root)
    out_root.mkdir(parents=True)
    samples = collect_samples(out_root)
    # Manifest for the upload script — relative path + size.
    manifest_path = out_root / "MANIFEST.txt"
    with manifest_path.open("w") as f:
        for s in samples:
            f.write(f"{len(s.bytes_):>10}  {s.rel_path}\n")
    total = sum(len(s.bytes_) for s in samples)
    print(f"wrote {len(samples)} samples ({total:,} bytes) under {out_root}")
    print(f"manifest at {manifest_path.relative_to(out_root.parent)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
