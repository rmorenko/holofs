# ---------------------------------------------------------------------------
# Deterministic-but-decent PNG / WAV writers.  Hand-rolled to keep this
# script dependency-free (no PIL, no soundfile).
# ---------------------------------------------------------------------------


def write_png(path: Path, pixels: list[list[tuple[int, int, int]]]) -> None:
    h = len(pixels)
    w = len(pixels[0])
    hdr = struct.pack(">IIBBBBB", w, h, 8, 2, 0, 0, 0)
    raw = bytearray()
    for row in pixels:
        raw.append(0)  # filter byte
        for r, g, b in row:
            raw.append(r & 0xFF)
            raw.append(g & 0xFF)
            raw.append(b & 0xFF)
    idat = zlib.compress(bytes(raw), 9)

    def chunk(tag: bytes, data: bytes) -> bytes:
        return (
            struct.pack(">I", len(data))
            + tag
            + data
            + struct.pack(">I", zlib.crc32(tag + data) & 0xFFFFFFFF)
        )

    path.write_bytes(
        b"\x89PNG\r\n\x1a\n"
        + chunk(b"IHDR", hdr)
        + chunk(b"IDAT", idat)
        + chunk(b"IEND", b"")
    )


def write_wav(path: Path, samples: list[float], sample_rate: int = 44100) -> None:
    # 16-bit PCM mono.
    n = len(samples)
    pcm = bytearray()
    for s in samples:
        v = int(max(-1.0, min(1.0, s)) * 32767)
        pcm.extend(struct.pack("<h", v))
    chunk_size = 36 + len(pcm)
    header = (
        b"RIFF"
        + struct.pack("<I", chunk_size)
        + b"WAVE"
        + b"fmt "
        + struct.pack("<IHHIIHH", 16, 1, 1, sample_rate, sample_rate * 2, 2, 16)
        + b"data"
        + struct.pack("<I", len(pcm))
    )
    path.write_bytes(header + bytes(pcm))


# ---------------------------------------------------------------------------
# Cheap deterministic PRNG (LCG).  Same seed → same output bytes.  Avoids
# pulling random.Random's Mersenne Twister so a parallel Rust / Go port of
# this generator could match byte-for-byte if anyone ever wants that.
# ---------------------------------------------------------------------------


class LCG:
    def __init__(self, seed: int = 0xC0FFEE) -> None:
        self.state = seed & 0xFFFFFFFF

    def next_u32(self) -> int:
        # Numerical Recipes constants — fine for fixtures, not for crypto.
        self.state = (self.state * 1664525 + 1013904223) & 0xFFFFFFFF
        return self.state

    def byte(self) -> int:
        return self.next_u32() & 0xFF

    def f01(self) -> float:
        return self.next_u32() / 0xFFFFFFFF


